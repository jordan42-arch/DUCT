#!/usr/bin/env python3
"""Regenerate logs/comparison_results.md from the raw cell metrics. Refuses to
put cells with mismatched protocol (lookback, horizon) in the same row."""

import argparse
import json
import os
from collections import defaultdict

MODELS = ["Naive", "DLinear", "iTransformer", "PatchTST",
          "TimeMixer", "PAttn", "WPMixer", "FreTS", "TSMixer", "DUCT"]
OURS = "DUCT"
DISPLAY = {m: (f"{m} (ours)" if m == OURS else m) for m in MODELS}

LONG_DATASETS = ["ETTh1", "ETTh2", "ETTm1", "ETTm2", "electricity",
                 "traffic", "weather", "exchange_rate", "solar"]
PEMS_DATASETS = ["PEMS03", "PEMS04", "PEMS07", "PEMS08"]
CLOUD_DATASETS = ["FaaS_Small", "FaaS_Medium", "FaaS_Large",
                  "IaaS_Small", "IaaS_Medium", "IaaS_Large"]


def load(comparison_root):
    """model -> (dataset, pred_len) -> record. Missing cells simply stay absent."""
    res = defaultdict(dict)

    duct_glob = os.path.join(comparison_root, OURS)
    if os.path.isdir(duct_glob):
        for dataset in sorted(os.listdir(duct_glob)):
            cells = os.path.join(duct_glob, dataset, "cells")
            if not os.path.isdir(cells):
                continue
            for cell in sorted(os.listdir(cells)):
                path = os.path.join(cells, cell, "metrics.json")
                if not os.path.exists(path):
                    continue
                with open(path) as f:
                    rec = json.load(f)[OURS]
                res[OURS][(rec["dataset"], rec["pred_len"])] = rec

    by_model = os.path.join(comparison_root, "by_model")
    if os.path.isdir(by_model):
        for model in sorted(os.listdir(by_model)):
            path = os.path.join(by_model, model, "all_datasets", "metrics.json")
            if not os.path.exists(path):
                continue
            with open(path) as f:
                agg = json.load(f)
            for key, rec in agg.items():
                if not isinstance(rec, dict) or rec.get("is_aggregate"):
                    continue
                if "dataset" not in rec:
                    continue
                res[model][(rec["dataset"], rec["pred_len"])] = rec
    return res


def comparable_cells(res, models):
    """-> (cells, skipped). Rejections are reported, not silently averaged over."""
    cells, skipped = [], []
    keys = sorted({k for m in models for k in res.get(m, {})},
                  key=lambda k: (k[0], k[1]))
    for key in keys:
        missing = [m for m in models if key not in res.get(m, {})]
        if missing:
            skipped.append((key, "missing for " + ", ".join(missing)))
            continue
        lookbacks = {res[m][key].get("lookback") for m in models}
        if len(lookbacks) > 1:
            detail = ", ".join(f"{m}={res[m][key].get('lookback')}" for m in models)
            skipped.append((key, f"lookback mismatch ({detail})"))
            continue
        cells.append(key)
    return cells, skipped


def fmt(rec):
    return f"{rec['mse']:.4f} / {rec['mae']:.4f}"


def table(out, header, rows):
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "|".join(["---" if i == 0 else "---:" for i in range(len(header))]) + "|")
    out.extend(rows)
    out.append("")


def marked(res, cells, model, keys):
    """Mean (mse, mae) for `model` over `keys`."""
    del cells
    vals = [res[model][k] for k in keys]
    mse = sum(v["mse"] for v in vals) / len(vals)
    mae = sum(v["mae"] for v in vals) / len(vals)
    return mse, mae


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="logs/comparison")
    ap.add_argument("--out", default="logs/comparison_results.md")
    ap.add_argument(
        "--models", nargs="+", choices=MODELS,
        help="Models to compare. Defaults to every registered comparison model.",
    )
    args = ap.parse_args()
    models = args.models or MODELS

    res = load(args.root)
    cells, skipped = comparable_cells(res, models)
    if not cells:
        raise SystemExit("no comparable cells found under " + args.root)

    present = {ds for ds, _ in cells}
    long_ds = [d for d in LONG_DATASETS if d in present]
    pems_ds = [d for d in PEMS_DATASETS if d in present]
    cloud_ds = [d for d in CLOUD_DATASETS if d in present]

    out = []
    out.append("# Comparison Results")
    out.append("")
    out.append(f"Generated by `scripts/comparison/make_comparison_results.py` from `{args.root}/`.")
    out.append("")
    out.append("Models: " + ", ".join(DISPLAY[m] for m in models) + ".")
    out.append("")
    out.append("Metric format: `MSE / MAE`; lower is better. Bold marks the lowest MSE in that row.")
    out.append("")
    out.append("All models in a given row share the same lookback and prediction horizon. "
               "ETT/electricity/traffic/weather/exchange_rate/solar use lookback 96 with "
               "horizons 96/192/336/720; PEMS uses lookback 48 with horizons 12/24/36/48.")
    out.append("")

    out.append(f"## Overall Average Across All {len(cells)} Comparable Cells")
    out.append("")
    ranked = []
    for m in models:
        mse, mae = marked(res, cells, m, cells)
        wins = sum(1 for k in cells
                   if min(res[x][k]["mse"] for x in models) == res[m][k]["mse"])
        ranked.append((mse, mae, m, wins))
    rows = []
    for i, (mse, mae, m, wins) in enumerate(sorted(ranked), 1):
        rows.append(f"| {i} | {DISPLAY[m]} | {mse:.4f} | {mae:.4f} | {len(cells)} | {wins} |")
    table(out, ["Rank", "Model", "Avg MSE", "Avg MAE", "Cells", "Best-MSE Cells"], rows)

    for title, group in (("Long-Horizon Datasets (lookback 96)", long_ds),
                         ("PEMS Datasets (lookback 48)", pems_ds),
                         ("CloudTS Datasets (lookback 144)", cloud_ds)):
        if not group:
            continue
        sub = [k for k in cells if k[0] in group]
        out.append(f"### {title}")
        out.append("")
        ranked = []
        for m in models:
            mse, mae = marked(res, cells, m, sub)
            wins = sum(1 for k in sub
                       if min(res[x][k]["mse"] for x in models) == res[m][k]["mse"])
            ranked.append((mse, mae, m, wins))
        rows = []
        for i, (mse, mae, m, wins) in enumerate(sorted(ranked), 1):
            rows.append(f"| {i} | {DISPLAY[m]} | {mse:.4f} | {mae:.4f} | {len(sub)} | {wins} |")
        table(out, ["Rank", "Model", "Avg MSE", "Avg MAE", "Cells", "Best-MSE Cells"], rows)

    out.append("## Dataset Average")
    out.append("")
    rows = []
    all_datasets = long_ds + pems_ds + cloud_ds
    for ds in all_datasets:
        keys = [k for k in cells if k[0] == ds]
        vals = {m: marked(res, cells, m, keys) for m in models}
        best = min(v[0] for v in vals.values())
        cellsf = []
        for m in models:
            mse, mae = vals[m]
            text = f"{mse:.4f} / {mae:.4f}"
            cellsf.append(f"**{text}**" if mse == best else text)
        rows.append(f"| {ds} | " + " | ".join(cellsf) + " |")
    table(out, ["Dataset"] + [DISPLAY[m] for m in models], rows)

    out.append("## Detailed Results By Dataset")
    out.append("")
    for ds in all_datasets:
        keys = sorted([k for k in cells if k[0] == ds], key=lambda k: k[1])
        if not keys:
            continue
        out.append(f"### {ds}")
        out.append("")
        rows = []
        for key in keys:
            best = min(res[m][key]["mse"] for m in models)
            cellsf = []
            for m in models:
                text = fmt(res[m][key])
                cellsf.append(f"**{text}**" if res[m][key]["mse"] == best else text)
            rows.append(f"| {key[1]} | " + " | ".join(cellsf) + " |")
        table(out, ["Horizon"] + [DISPLAY[m] for m in models], rows)

    if skipped:
        out.append("## Excluded Cells")
        out.append("")
        out.append("These cells are not in any table above because the models did not "
                   "run them under a shared protocol:")
        out.append("")
        for (ds, pl), why in skipped:
            out.append(f"- `{ds}` pl{pl}: {why}")
        out.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print(f"wrote {args.out}: {len(cells)} comparable cells, {len(skipped)} excluded")
    for (ds, pl), why in skipped:
        print(f"  excluded {ds} pl{pl}: {why}")


if __name__ == "__main__":
    main()
